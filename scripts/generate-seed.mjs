// Generates supabase/seed.sql from scripts/catalog.mjs.
// Usage: node scripts/generate-seed.mjs
// The seed is idempotent: courses that already exist (by slug) are skipped.
import { writeFileSync } from 'node:fs';
import { catalog } from './catalog.mjs';

const q = (s) => (s == null ? 'null' : `'${String(s).replace(/'/g, "''")}'`);
const j = (o) => `${q(JSON.stringify(o))}::jsonb`;
const arr = (a) => `array[${a.map(q).join(', ')}]::text[]`;

const placeholder = {
  nl: '> **Lesinhoud in voorbereiding.** Deze les wordt aangevuld en gecontroleerd voordat de cursus wordt gepubliceerd.',
  en: '> **Lesson content in preparation.** This lesson will be completed and reviewed before the course is published.',
};
const certReq = {
  nl: 'Voltooi alle verplichte lessen, lever de praktijkopdracht in (beoordeeld als goedgekeurd) en slaag voor het eindexamen met minimaal 70%.',
  en: 'Complete all mandatory lessons, submit the practical assignment (reviewed as approved) and pass the final exam with at least 70%.',
};

let sql = `-- ARA AI Academy – base data (generated by scripts/generate-seed.mjs; do not edit by hand)
-- Safe to run multiple times. Contains NO demo users or demo payments.

insert into public.academy_settings (id) values (1) on conflict (id) do nothing;

insert into public.payment_methods (code, kind, name, instructions, requires_proof, requires_reference, is_active, sort_order)
values
  ('bank_transfer', 'bank_transfer',
   ${j({ nl: 'Bankoverschrijving', en: 'Bank transfer' })},
   ${j({
     nl: 'Maak het cursusbedrag over naar de rekening van ARA AI Solutions.\n\n**Bank:** _in te vullen door beheerder_\n**Rekeningnummer:** _in te vullen door beheerder_\n**T.n.v.:** ARA AI Solutions\n\nVermeld je naam en de cursus als omschrijving en upload daarna je betaalbewijs.',
     en: 'Transfer the course fee to the ARA AI Solutions account.\n\n**Bank:** _to be configured by the administrator_\n**Account number:** _to be configured by the administrator_\n**Account holder:** ARA AI Solutions\n\nUse your name and the course as the description, then upload your proof of payment.',
   })}, true, true, true, 1),
  ('mobile_payment', 'mobile_money',
   ${j({ nl: 'Mobiel betalen', en: 'Mobile payment' })},
   ${j({
     nl: 'Betaal via een lokale mobiele betaaldienst. De beheerder vult hier de exacte gegevens in.\n\nUpload na betaling een schermafbeelding van de bevestiging.',
     en: 'Pay with a local mobile payment service. The administrator will add the exact details here.\n\nAfter paying, upload a screenshot of the confirmation.',
   })}, true, true, false, 2),
  ('cash', 'cash',
   ${j({ nl: 'Contante betaling', en: 'Cash payment' })},
   ${j({
     nl: 'Betaal contant op het kantoor van ARA AI Solutions. Je ontvangt een kwitantie; vul het kwitantienummer in als referentie.',
     en: 'Pay in cash at the ARA AI Solutions office. You will receive a receipt; enter the receipt number as the reference.',
   })}, false, true, true, 3)
on conflict (code) do nothing;
`;

catalog.forEach((c, ci) => {
  sql += `\n-- ${c.en.title}\ndo $seed$\ndeclare v_course uuid; v_module uuid; v_lesson uuid; v_quiz uuid; v_question uuid;\nbegin\n`;
  sql += `  if exists (select 1 from public.courses where slug = ${q(c.slug)}) then return; end if;\n`;
  sql += `  insert into public.courses (slug, status, level, price, currency, access_days, duration_weeks, estimated_hours, is_featured, sort_order)\n`;
  sql += `  values (${q(c.slug)}, 'draft', '${c.level}', 0, 'SRD', 90, ${c.weeks}, ${c.hours}, ${c.featured ? 'true' : 'false'}, ${ci + 1})\n  returning id into v_course;\n`;
  for (const loc of ['nl', 'en']) {
    const t = c[loc];
    sql += `  insert into public.course_translations (course_id, locale, title, subtitle, description, objectives, target_audience, certificate_requirements)\n`;
    sql += `  values (v_course, '${loc}', ${q(t.title)}, ${q(t.subtitle)}, ${q(t.description)}, ${arr(t.objectives)}, ${q(t.audience)}, ${q(certReq[loc])});\n`;
  }
  c.modules.forEach((m, mi) => {
    sql += `  insert into public.course_modules (course_id, position, title) values (v_course, ${mi + 1}, ${j({ nl: m.nl, en: m.en })}) returning id into v_module;\n`;
    const lessons = [...m.lessons];
    if (m.assignment) lessons.push(['assignment', m.assignment[0], m.assignment[1]]);
    lessons.push(['quiz', `Modulequiz: ${m.nl}`, `Module quiz: ${m.en}`]);
    lessons.forEach(([type, nl, en], li) => {
      sql += `  insert into public.lessons (module_id, course_id, position, type, title, estimated_minutes, is_mandatory, status)\n`;
      sql += `  values (v_module, v_course, ${li + 1}, '${type}', ${j({ nl, en })}, ${type === 'video' ? 15 : type === 'assignment' ? 90 : type === 'quiz' ? 15 : 20}, true, 'draft') returning id into v_lesson;\n`;
      sql += `  insert into public.lesson_contents (lesson_id, course_id, body) values (v_lesson, v_course, ${j(placeholder)});\n`;
      if (type === 'assignment') {
        sql += `  insert into public.assignments (lesson_id, course_id, instructions, submission_type, is_required, requires_review)\n`;
        sql += `  values (v_lesson, v_course, ${j({
          nl: 'Opdrachtomschrijving in voorbereiding. De beheerder voegt de exacte instructies en beoordelingscriteria toe.',
          en: 'Assignment brief in preparation. The administrator will add the exact instructions and assessment criteria.',
        })}, 'any', true, true);\n`;
      }
      if (type === 'quiz') {
        sql += `  insert into public.quizzes (course_id, lesson_id, kind, title, passing_score, status)\n`;
        sql += `  values (v_course, v_lesson, 'quiz', ${j({ nl, en })}, 70, 'draft');\n`;
      }
    });
  });
  // final exam
  sql += `  insert into public.quizzes (course_id, kind, title, instructions, passing_score, time_limit_minutes, max_attempts, retake_wait_hours, status)\n`;
  sql += `  values (v_course, 'final_exam', ${j({ nl: `Eindexamen ${c.nl.title}`, en: `Final exam ${c.en.title}` })}, ${j({
    nl: 'Je hebt 60 minuten en maximaal 3 pogingen. Je slaagt met een score van minimaal 70%. Na een niet-geslaagde poging kun je na 24 uur opnieuw deelnemen.',
    en: 'You have 60 minutes and up to 3 attempts. You pass with a score of at least 70%. After an unsuccessful attempt you can retake the exam after 24 hours.',
  })}, 70, 60, 3, 24, 'draft') returning id into v_quiz;\n`;
  (c.exam ?? []).forEach((qq, qi) => {
    sql += `  insert into public.quiz_questions (quiz_id, type, prompt, accepted_answers, points, position)\n`;
    sql += `  values (v_quiz, '${qq.type}', ${j({ nl: qq.nl, en: qq.en })}, ${j(qq.accepted ?? {})}, 1, ${qi + 1}) returning id into v_question;\n`;
    (qq.options ?? []).forEach(([nl, en, correct], oi) => {
      sql += `  insert into public.quiz_options (question_id, label, is_correct, position) values (v_question, ${j({ nl, en })}, ${correct}, ${oi + 1});\n`;
    });
  });
  sql += `end $seed$;\n`;
});

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql);
console.log(`seed.sql written (${catalog.length} courses)`);
